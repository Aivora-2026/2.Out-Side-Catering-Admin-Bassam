    // A second record keeps EVERYTHING the customer entered on this page, in separate columns (buffet type, package, price, menu items, terms accepted).
    // It is sent after the booking itself succeeds, so a problem here can never stop a booking.
    function saveDetails(ref) {
      var v = String(f.get('buffet') || ''), nm = BUF[v] || ['', ''], code = f.get('package') ? String(f.get('package')) : '', pk = code ? pkgFind(code) : null;
      var cbP = cbPrice();
      var items = MENUS[v] ? cbFlat(v).filter(function (x) { return cbSel[x.id]; }).map(function (x) { return { ar: x.ar, en: x.en }; }) : [];
      var details = {
        booking_ref: ref == null ? '' : String(ref),
        full_name: payload.full_name, phone: payload.phone, national_id: payload.national_id,
        calendar_type: payload.calendar_type, event_date: payload.event_date, hijri_date: payload.hijri_date, event_time: payload.event_time,
        address: payload.address, city: payload.city, postal_code: payload.postal_code, guests: payload.guests,
        customer_notes: f.get('notes') || '', language: lang,
        buffet_type: v, buffet_name: nm[0], buffet_name_ar: nm[1],
        package_code: cbP ? (cbP.key === 'Breakfast' ? 'BF' : 'CB') + cbP.rate : code, package_label: cbP ? cbLabel('en') : (code ? pkgLabel(code, 'en', true) : ''), package_label_ar: cbP ? cbLabel('ar') : (code ? pkgLabel(code, 'ar', true) : ''),
        package_price: cbP ? cbP.total : (code ? pkgTotal(code) : null), menu_items: items,
        terms_accepted: !!accept.checked, terms_accepted_at: new Date().toISOString()
      };
      fetch(cfg.url + '/rest/v1/rpc/catering_save_booking_details', { method: 'POST', headers: headers, body: JSON.stringify({ p: details }) })
        .catch(function () {});
    }
    go.disabled = true; go.textContent = t('sending');
    fetch(cfg.url + '/rest/v1/rpc/catering_submit_booking', { method: 'POST', headers: headers, body: JSON.stringify({ p: payload }) })
      .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
      .then(function (ref) { saveDetails(ref); clearDraft(); showSummary(f, d, ref); })
      .catch(function () { showErr('errSend'); })
      .then(function () { go.disabled = false; go.textContent = t('submit'); });
